#!/usr/bin/env node
/**
 * Generate `dsh-compact-focus/cordis.patch.yml` from the standard agent preset
 * shipped by `@deepseek-ai/dsh-web-app`.
 *
 * A Loader override replaces the whole `preset-standard` config, so the shipped
 * plugin list must be restated. This script snapshots that list and swaps only
 * the compaction group:
 *
 *   compaction-basic  -> dsh-compact-focus            (focus-aware backend)
 *   command-compact   -> dsh-compact-focus/command    (optional focus argument)
 *   tool-result-pruner stays untouched
 *
 * Usage:
 *   node tools/gen-focus-patch.mjs <standard.patch.yml> <out-cordis.patch.yml>
 *
 * Re-run after a DSH upgrade that changes the standard preset.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const [, , sourceArg, outArg] = process.argv
if (sourceArg === undefined || outArg === undefined) {
  console.error('usage: node gen-focus-patch.mjs <standard.patch.yml> <out-cordis.patch.yml>')
  process.exit(2)
}

const source = readFileSync(sourceArg, 'utf8').replace(/\r\n/g, '\n').split('\n')

/** Locate `        plugins:` inside the shipped preset declaration. */
const pluginsHeader = source.findIndex((line) => /^ {8}plugins:\s*$/u.test(line))
if (pluginsHeader === -1) {
  console.error('error: cannot find the preset plugins list in the source file')
  process.exit(1)
}
const itemIndent = source.slice(pluginsHeader + 1).find((line) => /^ +- /u.test(line))
if (itemIndent === undefined) {
  console.error('error: cannot find the first preset plugin entry')
  process.exit(1)
}
const indentWidth = itemIndent.match(/^ +/u)[0].length
if (indentWidth < 4) {
  console.error(`error: unexpected plugin list indentation ${indentWidth}`)
  process.exit(1)
}

// Restated target entries sit at `      - ` (6 spaces); unindent the shipped list by 4.
const unindent = 4
const items = source
  .slice(pluginsHeader + 1)
  .filter((line, index, all) => !(index === all.length - 1 && line === ''))
  .map((line) => (line.startsWith(' '.repeat(unindent)) ? line.slice(unindent) : line))

const groupStart = items.findIndex((line) => /^ {6}- id: compaction\s*$/u.test(line))
if (groupStart === -1) {
  console.error('error: cannot find the compaction group in the standard preset')
  process.exit(1)
}
let groupEnd = items.length
for (let index = groupStart + 1; index < items.length; index += 1) {
  if (/^ {6}- /u.test(items[index])) {
    groupEnd = index
    break
  }
}

const replacement = [
  '      - id: compaction',
  '        name: cordis:group',
  '        group: true',
  '        isolate:',
  '          compaction: true',
  '          toolResultPruner: true',
  '        config:',
  '          - id: compaction-focus',
  "            name: 'dsh-compact-focus'",
  '          - id: command-compact-focus',
  "            name: 'dsh-compact-focus/command'",
  '          - id: tool-result-pruner',
  "            name: '@deepseek-ai/dsh-compaction-tool-result-pruner'",
  '            config:',
  '              thresholdChars: 8192',
  '              headChars: 4096',
  '              tailChars: 1024',
]

const nextItems = [...items.slice(0, groupStart), ...replacement, ...items.slice(groupEnd)]

const header = [
  '# dsh-compact-focus — directed compaction for DeepSeek Harness.',
  '#',
  '# Generated by tools/gen-focus-patch.mjs from the standard agent preset shipped',
  '# by @deepseek-ai/dsh-web-app 0.2.1-rc.1. A Loader override replaces the whole',
  '# preset config, so the shipped plugin list is restated below; only the',
  '# compaction group differs: the backend and the /compact command are replaced',
  '# by dsh-compact-focus so the command accepts an optional summary focus.',
  '#',
  '# Re-run the generator after a DSH upgrade that changes the standard preset.',
  '#',
  '# Disable or remove this bundle to get the shipped behavior back.',
  '- id: preset-standard',
  "  name: '@deepseek-ai/dsh-agent-preset'",
  '  config:',
  '    id: standard',
  '    order: 1',
  '    plugins:',
]

const output = [...header, ...nextItems].join('\n') + '\n'
writeFileSync(outArg, output)
console.log(`wrote ${outArg} (${output.split('\n').length - 1} lines)`)
